#!/usr/bin/env node
/*
 * Edit your own message, marked as edited (#287, ADR-0009).
 *
 * The edit path end to end, driven against the real `TaskService` over a real
 * (temp-file) `TaskStore` with a recording notifier, plus the real web thread
 * rendered to markup. The promises under test are the ones a reader of the
 * code cannot check by looking:
 *
 *   - **Author only** (rule 1), enforced in the service and not merely by the
 *     menu being absent. The other party, an observer and an admin are all
 *     refused.
 *   - **No time window, archival is the gate** (rule 2). Open, claimed and
 *     completed tasks take an edit; an archived one refuses it, matching its
 *     existing refusal of new messages. A message posted six weeks ago is as
 *     editable as one posted a minute ago.
 *   - **`(edited)`, and nothing more** (rule 3). No timestamp, and the previous
 *     wording is nowhere in the rendered thread.
 *   - **An edit may not empty a message** (rule 4). Deletion is #288.
 *   - **Silence** (rule 6), which is four separate promises and gets four
 *     assertions: no DM, no feed ping, no channel post; `at` unmoved so the
 *     message does not re-raise as unread; `updatedAt` unmoved so the task
 *     holds its place in the done list and the archive; and the DM cards
 *     refreshed in place through the silent sync path, quoting the correction.
 *   - **The label survives** (rule 5). The app's `Needs fixes` prefix is
 *     untouched by an edit that rewrites the author's words.
 *   - **History carries both sides** (rule 7).
 *
 * Run: `node --test scripts/message-edit-sim-test.mjs`.
 */
import assert from "node:assert/strict";
import { promises as fsp, mkdtempSync, rmSync } from "node:fs";
import os from "node:os";
import path, { join } from "node:path";
import test from "node:test";
import { fileURLToPath, pathToFileURL } from "node:url";

import { build } from "esbuild";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";

import { ACTION_LABELS, needsFixesNote } from "../packages/shared/dist/labels.js";
import { REVIEW_NOTE_EDITED_ACTION } from "../packages/shared/dist/history.js";
import {
  MESSAGE_EDITED_MARKER,
  canEditMessage,
  editMessageInThread,
  hasUnreadNoteForViewer,
  messageEditRefusal,
  noteBodyText,
  unreadNoteFor
} from "../packages/shared/dist/notes.js";
import { TaskStore } from "../apps/server/dist/store.js";
import { SseHub } from "../apps/server/dist/sse.js";
import { TaskService } from "../apps/server/dist/task-service.js";

const REPO = fileURLToPath(new URL("..", import.meta.url));

/* Same trick as `message-identity-sim-test.mjs`: the thread is TSX with a
   relative import, so esbuild bundles it into something node can load, and the
   promise about what the thread shows is checked against real markup. */
const scratch = mkdtempSync(join(REPO, "node_modules", ".message-edit-"));
process.on("exit", () => rmSync(scratch, { recursive: true, force: true }));
const threadModule = join(scratch, "thread.mjs");
await build({
  entryPoints: [join(REPO, "apps/web/src/thread.tsx")],
  outfile: threadModule,
  bundle: true,
  format: "esm",
  jsx: "automatic",
  external: ["react", "react/jsx-runtime", "@loan-tasks/shared"],
  logLevel: "silent"
});
const { ThreadMessages } = await import(pathToFileURL(threadModule).href);

const { recentNoteThread } = await import(pathToFileURL(join(REPO, "apps/server/dist/bot.js")).href);

const CREATOR = { id: "creator-1", displayName: "Dana Requester", roles: ["LOAN_OFFICER"] };
const ASSIGNEE = { id: "checker-1", displayName: "Casey Checker", roles: ["LOAN_OFFICER", "FILE_CHECKER"] };
const OBSERVER = { id: "observer-1", displayName: "Sam Bystander", roles: ["LOAN_OFFICER"] };
const ADMIN = { id: "admin-1", displayName: "Alex Admin", roles: ["ADMIN"] };

const CONFIG = {
  businessTimezone: "America/Los_Angeles",
  businessStartHour: 8,
  businessStartMinute: 30,
  businessEndHour: 17,
  businessEndMinute: 30,
  archiveRetentionDays: 90
};

const setup = async () => {
  const dir = await fsp.mkdtemp(path.join(os.tmpdir(), "message-edit-sim-"));
  const store = new TaskStore(path.join(dir, "tasks.json"));
  await store.init();
  const events = [];
  const service = new TaskService(
    store,
    { notify: async (event) => { events.push(event); }, canReachDm: async () => true },
    new SseHub(),
    CONFIG
  );
  return { service, store, events };
};

/* A claimed VALUE task with one message on it from `author`, and every
   notification the setting-up generated already drained — so anything left in
   `events` after an edit was generated BY the edit. */
const taskWithMessage = async (service, events, { author = CREATOR, text = "Comps look thin." } = {}) => {
  const task = await service.createTask(
    { folderName: "Smith-1042", taskType: "VALUE", notes: "Please value this.", urgency: "GREEN" },
    CREATOR
  );
  await service.claimTask(task.id, ASSIGNEE);
  const withNote = await service.addReviewNote(task.id, text, author);
  await service.settleBackgroundWork();
  events.length = 0;
  return { taskId: task.id, message: withNote.reviewNotes[0] };
};

const rejects = (fn, pattern, label) =>
  assert.rejects(fn, (error) => {
    assert.match(error.message, pattern, `${label}: the refusal names the rule (got "${error.message}")`);
    return true;
  }, label);

const renderThread = (task, viewerId, onEditMessage) =>
  renderToStaticMarkup(
    createElement(ThreadMessages, {
      task,
      viewerId,
      canReply: true,
      ...(onEditMessage ? { onEditMessage } : {})
    })
  );

const triggerCount = (markup) => (markup.match(/msg-menu-trigger/g) ?? []).length;

/* ── The author, and only the author (rule 1) ────────────────────────────── */

test("the author can correct their own message", async () => {
  const { service, events } = await setup();
  const { taskId, message } = await taskWithMessage(service, events);

  const updated = await service.editReviewNote(taskId, message.id, "Comps look thin on the north side.", CREATOR);
  const [edited] = updated.reviewNotes;

  assert.equal(edited.text, "Comps look thin on the north side.", "the words are the ones they just typed");
  assert.equal(edited.id, message.id, "and it is still the same message");
  assert.equal(edited.edited, true, "carrying the marker rule 3 asks for");
});

test("the other party, an observer and an admin are all refused by the service", async () => {
  const { service, events } = await setup();
  const { taskId, message } = await taskWithMessage(service, events);

  for (const stranger of [ASSIGNEE, OBSERVER, ADMIN]) {
    await rejects(
      () => service.editReviewNote(taskId, message.id, "not mine to change", stranger),
      /Only the person who wrote/,
      stranger.displayName
    );
  }

  /* ADR-0003: back-end access confers nothing over other people's work, and the
     admin refusal above is that sentence rather than a missing role check. */
  const store = await service.store.findTask(taskId);
  assert.equal(store.reviewNotes[0].text, "Comps look thin.", "and nothing they sent landed");
  assert.equal(store.reviewNotes[0].edited, undefined, "not even the marker");
});

test("the refusal and the menu read the same rule", () => {
  /* The web hides the control off `canEditMessage` and the server throws off
     `messageEditRefusal`. Two surfaces, one rule — asserted rather than assumed,
     because "hidden but permitted" and "shown but refused" are the two bugs a
     second copy of a permission rule produces. */
  const task = { status: "CLAIMED" };
  const mine = { by: { id: CREATOR.id, displayName: CREATOR.displayName } };
  assert.equal(canEditMessage(task, mine, CREATOR), true);
  assert.equal(messageEditRefusal(task, mine, CREATOR), undefined);
  assert.equal(canEditMessage(task, mine, ASSIGNEE), false);
  assert.ok(messageEditRefusal(task, mine, ASSIGNEE));
  assert.equal(canEditMessage({ status: "ARCHIVED" }, mine, CREATOR), false);
});

/* ── No window; archival is the gate (rule 2) ────────────────────────────── */

test("an open, a claimed and a completed task all take an edit", async () => {
  const { service, events } = await setup();

  const open = await service.createTask(
    { folderName: "Open-1", taskType: "VALUE", notes: "ask", urgency: "GREEN" },
    CREATOR
  );
  const openNoted = await service.addReviewNote(open.id, "first thought", CREATOR);
  await service.settleBackgroundWork();
  const openEdited = await service.editReviewNote(open.id, openNoted.reviewNotes[0].id, "second thought", CREATOR);
  assert.equal(openEdited.status, "OPEN", "and the status is untouched by the edit");
  assert.equal(openEdited.reviewNotes[0].text, "second thought");

  const { taskId, message } = await taskWithMessage(service, events);
  const claimedEdited = await service.editReviewNote(taskId, message.id, "on a claimed task", CREATOR);
  assert.equal(claimedEdited.status, "CLAIMED");
  assert.equal(claimedEdited.reviewNotes[0].text, "on a claimed task");

  /* A completed task's conversation is deliberately still open — a message can
     be posted to one — so refusing a typo fix in it would not be a defensible
     pair of rules. */
  await service.transitionStatus(taskId, "COMPLETED", ASSIGNEE);
  await service.settleBackgroundWork();
  const completedEdited = await service.editReviewNote(taskId, message.id, "on a completed task", CREATOR);
  assert.equal(completedEdited.status, "COMPLETED", "still completed");
  assert.equal(completedEdited.reviewNotes[0].text, "on a completed task");
});

test("an archived task refuses an edit, as it already refuses new messages", async () => {
  const { service, events } = await setup();
  const { taskId, message } = await taskWithMessage(service, events);
  await service.transitionStatus(taskId, "COMPLETED", ASSIGNEE);
  await service.transitionStatus(taskId, "ARCHIVED", CREATOR);
  await service.settleBackgroundWork();

  await rejects(
    () => service.editReviewNote(taskId, message.id, "too late", CREATOR),
    /archived/i,
    "an archived task"
  );
  await rejects(() => service.addReviewNote(taskId, "too late", CREATOR), /closed/i, "and so does a new message");
});

test("a message posted six weeks ago is as editable as one posted a minute ago", async () => {
  const { service, store, events } = await setup();
  const { taskId, message } = await taskWithMessage(service, events);

  const longAgo = new Date(Date.now() - 42 * 86400000).toISOString();
  await store.updateTask(taskId, (current) => ({
    task: { ...current, reviewNotes: current.reviewNotes.map((note) => ({ ...note, at: longAgo })) }
  }));

  const updated = await service.editReviewNote(taskId, message.id, "still fixable", CREATOR);
  assert.equal(updated.reviewNotes[0].text, "still fixable", "no window closed behind it");
  assert.equal(updated.reviewNotes[0].at, longAgo, "and the post time is where it was");
});

/* ── An edit may not empty a message (rule 4) ────────────────────────────── */

test("an empty or whitespace-only edit is refused", async () => {
  const { service, events } = await setup();
  const { taskId, message } = await taskWithMessage(service, events);

  for (const blank of ["", "   ", "\n\t "]) {
    await rejects(
      () => service.editReviewNote(taskId, message.id, blank, CREATOR),
      /cannot be emptied/i,
      JSON.stringify(blank)
    );
  }
  const still = await service.store.findTask(taskId);
  assert.equal(still.reviewNotes[0].text, "Comps look thin.", "the message is untouched");
});

test("an edit that changes nothing is not an edit", async () => {
  const { service, events } = await setup();
  const { taskId, message } = await taskWithMessage(service, events);

  const same = await service.editReviewNote(taskId, message.id, "Comps look thin.", CREATOR);
  await service.settleBackgroundWork();
  assert.equal(same.reviewNotes[0].edited, undefined, "no marker for a change that was not one");
  assert.equal(events.length, 0, "and no card resync either");
  const history = await service.store.allHistoryForTask(taskId);
  assert.equal(history.filter((e) => e.action === REVIEW_NOTE_EDITED_ACTION).length, 0, "and no history row");
});

/* ── Silence, on every channel (rule 6) ──────────────────────────────────── */

test("an edit sends no DM, no feed ping and no channel post — only the silent card refresh", async () => {
  const { service, events } = await setup();
  const { taskId, message } = await taskWithMessage(service, events);

  await service.editReviewNote(taskId, message.id, "Comps look thin on the north side.", CREATOR);
  await service.settleBackgroundWork();

  const targets = events.map((event) => event.target);
  assert.deepEqual(targets, ["DM_CARD_SYNC"], `the only thing that goes out is the quiet resync (got ${targets.join(", ")})`);
  for (const target of targets) {
    assert.ok(!target.startsWith("CHANNEL"), "nothing reaches the channel");
    assert.notEqual(target, "ACTIVITY_FEED", "nothing reaches the activity feed");
    assert.notEqual(target, "DM_NOTE", "and nobody is DMed about it");
  }
});

test("the task does not move in the done list or the archive", async () => {
  const { service, store, events } = await setup();
  const { taskId, message } = await taskWithMessage(service, events);
  await service.transitionStatus(taskId, "COMPLETED", ASSIGNEE);
  await service.settleBackgroundWork();

  /* A second task finished AFTER the first, so the list has an order that a
     bumped `updatedAt` would visibly break. `allTasks` sorts by `updatedAt`
     descending, which is the sort the done list and the archive use. */
  const later = await service.createTask(
    { folderName: "Later-9", taskType: "VALUE", notes: "ask", urgency: "GREEN" },
    CREATOR
  );
  await service.claimTask(later.id, ASSIGNEE);
  await service.transitionStatus(later.id, "COMPLETED", ASSIGNEE);
  await service.settleBackgroundWork();

  const before = await service.store.findTask(taskId);
  const orderBefore = (await store.allTasks()).map((task) => task.id);

  await service.editReviewNote(taskId, message.id, "one letter fixed", CREATOR);
  await service.settleBackgroundWork();

  const after = await service.store.findTask(taskId);
  assert.equal(after.updatedAt, before.updatedAt, "the carve-out: a correction does not stamp updatedAt");
  assert.equal(after.completedAt, before.completedAt, "and does not restamp the completion either");
  assert.deepEqual(await store.allTasks().then((tasks) => tasks.map((t) => t.id)), orderBefore,
    "so the old task stays below the one genuinely finished later");
});

test("a viewer who had already read the message does not see it as unread again", async () => {
  const { service, events } = await setup();
  const { taskId, message } = await taskWithMessage(service, events, { author: ASSIGNEE, text: "page 3 looks wrong" });

  const before = await service.store.findTask(taskId);
  /* The creator has read up to the message's own timestamp — the value the
     shared rule compares, and the one an edit must not move. */
  const seen = before.reviewNotes[0].at;
  assert.equal(hasUnreadNoteForViewer(before, CREATOR, seen), false, "nothing outstanding before the edit");

  const after = await service.editReviewNote(taskId, message.id, "page 4 looks wrong", ASSIGNEE);
  assert.equal(after.reviewNotes[0].at, seen, "the message keeps its original post time");
  assert.equal(hasUnreadNoteForViewer(after, CREATOR, seen), false, "so it does not re-raise at a reader who was done");
  assert.equal(unreadNoteFor(after, CREATOR, seen), undefined);
  /* And somebody who had NOT read it still has it waiting — the rule did not
     stop working, it just did not fire. */
  assert.equal(unreadNoteFor(after, CREATOR, undefined), seen, "a reader who never read it still has it");
});

test("a Teams card quoting the thread shows the correction after its background refresh", async () => {
  const { service, events } = await setup();
  const { taskId, message } = await taskWithMessage(service, events);

  const updated = await service.editReviewNote(taskId, message.id, "Comps look thin on the north side.", CREATOR);
  await service.settleBackgroundWork();

  const [sync] = events;
  assert.equal(sync.target, "DM_CARD_SYNC", "the refresh rides the silent sync, not a new nudge");
  assert.deepEqual(
    recentNoteThread(sync.task).map((entry) => entry.text),
    ["Comps look thin on the north side."],
    "and the card it redraws quotes the corrected words"
  );
  assert.deepEqual(recentNoteThread(updated).map((entry) => entry.text), ["Comps look thin on the north side."]);
});

/* ── The label survives (rule 5) ─────────────────────────────────────────── */

test("editing an app-prefixed message leaves the prefix intact", async () => {
  const { service, events } = await setup();
  const task = await service.createTask(
    { folderName: "Jones-77", taskType: "LOI", notes: "terms attached", urgency: "GREEN" },
    CREATOR
  );
  await service.claimTask(task.id, ASSIGNEE);
  const sent = await service.transitionStatus(task.id, "NEEDS_REVIEW", ASSIGNEE, "borrower name is misspelt");
  await service.settleBackgroundWork();
  events.length = 0;

  const sendBack = sent.reviewNotes[0];
  assert.equal(sendBack.label, ACTION_LABELS.NEEDS_FIXES, "the app wrote the label");

  const fixed = await service.editReviewNote(task.id, sendBack.id, "borrower name is misspelt on page 3", ASSIGNEE);
  const after = fixed.reviewNotes[0];
  assert.equal(after.label, ACTION_LABELS.NEEDS_FIXES, "and the edit did not reach it");
  assert.equal(after.text, "borrower name is misspelt on page 3", "only the author's own words moved");
  assert.equal(
    noteBodyText(after),
    needsFixesNote("borrower name is misspelt on page 3"),
    "so the row still reads as a send-back, character for character"
  );
});

test("the pure transform is what guarantees it, on every message at once", () => {
  /* The shape of an edit decided in one place: text and marker in, everything
     that addresses or dates or labels the message left alone. */
  const thread = [
    { id: "a", text: "one", by: { id: CREATOR.id, displayName: "Dana" }, at: "2026-08-01T00:00:00.000Z" },
    { id: "b", label: ACTION_LABELS.NEEDS_FIXES, text: "two", by: { id: ASSIGNEE.id, displayName: "Casey" }, at: "2026-08-02T00:00:00.000Z" }
  ];
  const edited = editMessageInThread(thread, "b", "two, corrected");
  assert.equal(edited[0], thread[0], "an untouched message is the same object");
  assert.deepEqual(edited[1], {
    id: "b",
    label: ACTION_LABELS.NEEDS_FIXES,
    text: "two, corrected",
    by: { id: ASSIGNEE.id, displayName: "Casey" },
    at: "2026-08-02T00:00:00.000Z",
    edited: true
  });
  assert.equal(editMessageInThread(edited, "b", "two, corrected")[1], edited[1], "and a no-op edit rewrites nothing");
});

/* ── History carries both sides (rule 7) ─────────────────────────────────── */

test("each edit lands in history with the text on both sides", async () => {
  const { service, events } = await setup();
  const { taskId, message } = await taskWithMessage(service, events);

  await service.editReviewNote(taskId, message.id, "Comps look thin on the north side.", CREATOR);
  await service.editReviewNote(taskId, message.id, "Comps look thin on the south side.", CREATOR);
  await service.settleBackgroundWork();

  const rows = (await service.store.allHistoryForTask(taskId)).filter((e) => e.action === REVIEW_NOTE_EDITED_ACTION);
  assert.equal(rows.length, 2, "one row per edit");
  assert.match(rows[0].detail, /"Comps look thin\."/, "the wording before");
  assert.match(rows[0].detail, /"Comps look thin on the north side\."/, "and the wording after");
  assert.match(rows[1].detail, /"Comps look thin on the north side\."/, "the second edit's before is the first's after");
  assert.equal(rows[0].by.id, CREATOR.id, "attributed to the author who made it");
});

/* ── What the thread shows (rules 3 and 9) ───────────────────────────────── */

const threadTask = (notes, status = "CLAIMED") => ({
  taskType: "VALUE",
  status,
  notes: "Please value this.",
  createdBy: { id: CREATOR.id, displayName: CREATOR.displayName },
  createdAt: "2026-08-20T09:00:00.000Z",
  reviewNotes: notes
});

const MINE = {
  id: "m1",
  text: "Comps look thin on the north side.",
  edited: true,
  by: { id: CREATOR.id, displayName: CREATOR.displayName },
  at: "2026-08-20T10:00:00.000Z"
};
const THEIRS = {
  id: "m2",
  text: "Agreed, re-pulling them.",
  by: { id: ASSIGNEE.id, displayName: ASSIGNEE.displayName },
  at: "2026-08-20T11:00:00.000Z"
};

test("an edited message renders `(edited)`, with no timestamp and no way back", () => {
  const markup = renderThread(threadTask([MINE, THEIRS]), CREATOR.id, async () => {});
  assert.ok(markup.includes(MESSAGE_EDITED_MARKER), "the marker is there");
  assert.match(markup, /msg-edited/, "in its own muted span rather than inside the sentence");
  assert.ok(!markup.includes("Comps look thin.</div>"), "and the previous wording is not in the thread");
  /* Rule 3 refused an edit time. The row's byline still carries the message's
     own post time and nothing else, so "no timestamp" means no SECOND one. */
  const times = markup.match(/2026-08-20T\d\d/g) ?? [];
  assert.equal(times.length, 0, "no raw timestamp is printed beside the marker");
  const unedited = renderThread(threadTask([THEIRS]), ASSIGNEE.id, async () => {});
  assert.ok(!unedited.includes(MESSAGE_EDITED_MARKER), "and an untouched message says nothing");
});

test("the menu is drawn on your own messages and on nobody else's", () => {
  const asAuthor = renderThread(threadTask([MINE, THEIRS]), CREATOR.id, async () => {});
  assert.equal(triggerCount(asAuthor), 1, "one menu, on the one message the viewer wrote");

  const asOther = renderThread(threadTask([MINE, THEIRS]), ASSIGNEE.id, async () => {});
  assert.equal(triggerCount(asOther), 1, "and the other party gets one on theirs");

  const asObserver = renderThread(threadTask([MINE, THEIRS]), OBSERVER.id, async () => {});
  assert.equal(triggerCount(asObserver), 0, "an observer wrote nothing here, so gets nothing");
});

test("an archived task's thread offers no menu at all", () => {
  const archived = renderThread(threadTask([MINE, THEIRS], "ARCHIVED"), CREATOR.id, async () => {});
  assert.equal(triggerCount(archived), 0, "the conversation is closed, and so are its corrections");
});

test("a surface with nothing to save to renders the thread exactly as it did before", () => {
  const withHandler = renderThread(threadTask([MINE, THEIRS]), CREATOR.id, async () => {});
  const readOnly = renderThread(threadTask([MINE, THEIRS]), CREATOR.id, undefined);
  assert.equal(triggerCount(readOnly), 0);
  assert.ok(withHandler.length > readOnly.length, "the menu is the only difference");
  assert.ok(readOnly.includes(MESSAGE_EDITED_MARKER), "the marker is not part of the control");
});

test("the originating field is not a message and carries no menu", () => {
  /* On the five types whose request field still opens the thread, that first
     row is the task's ask, and its one door is `Edit Task` in the hamburger
     (ADR-0008 rule 4). Only what somebody posted is editable here. */
  const markup = renderThread(threadTask([]), CREATOR.id, async () => {});
  assert.ok(markup.includes("Please value this."), "the field still opens the thread");
  assert.equal(triggerCount(markup), 0, "with no per-message menu on it");
});
